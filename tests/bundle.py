#!/usr/bin/env python3
"""Bundle the plugin and its tests into one Luau chunk.

The Luau CLI gives each required module read-only globals and has no file
I/O, so tests can't hand modules a fake `tern` global. This wraps every
source file in a function inside one chunk where `tern` is a shared local,
with a small `require` that resolves "./x" and "../x" like Tern does.

Usage: python3 tests/bundle.py OUT.luau && luau OUT.luau
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ["host.luau", "window.luau", *sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "lib").glob("*.luau")),
           *sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "tests").glob("*.luau"))]
ENTRY = "tests/run"


def main() -> None:
    out = pathlib.Path(sys.argv[1])
    parts = [
        "-- generated by tests/bundle.py; do not edit",
        "local tern: any = nil",
        "local __mods = {}",
        "local __cache = {}",
        "local function __resolve(base, name)",
        "  local parts = {}",
        "  for seg in string.gmatch(base, '[^/]+') do table.insert(parts, seg) end",
        "  for seg in string.gmatch(name, '[^/]+') do",
        "    if seg == '..' then table.remove(parts) elseif seg ~= '.' then table.insert(parts, seg) end",
        "  end",
        "  return table.concat(parts, '/')",
        "end",
        "local __require_from",
        "local function __load(key)",
        "  if __cache[key] == nil then",
        "    local f = __mods[key] or __mods[key .. '/init'] or error('module not found: ' .. key)",
        "    local dir = string.match(key, '^(.*)/[^/]*$') or ''",
        "    __cache[key] = f(__require_from(dir)) or true",
        "  end",
        "  return __cache[key]",
        "end",
        "__require_from = function(dir)",
        "  return function(name) return __load(__resolve(dir, name)) end",
        "end",
    ]
    for rel in SOURCES:
        key = rel[: -len(".luau")]
        src = (ROOT / rel).read_text()
        # `--!strict` must be the first line of a file; inside the bundle it is just a comment.
        src = src.replace("--!strict", "-- (strict)", 1).replace("\nexport type ", "\ntype ")
        parts.append(f"__mods[{key!r}] = function(require)\n{src}\nend")
    parts.append(f"__load({ENTRY!r})")
    out.write_text("\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
